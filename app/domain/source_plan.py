"""Что именно спрашивать в этой проверке — и чего не покупать.

ЗАЧЕМ ЭТО ЕСТЬ. Проверка по умолчанию спрашивает все подключённые источники и
по дороге покупает ИНН по паспорту. Это правильно, когда отчёт несут в суд, и
расточительно, когда надо посмотреть ОДИН источник: владелец сформулировал это
прямо — «делать запросы отдельными (которые не дипсерч) и не получить ИНН, чтобы
не расходовать запросы в NewDB».

Счёт простой. Обращение к NewDB стоит 2 ₽, у должника с паспортом полная
проверка это пять обращений, и четыре из них не нужны, когда проверяешь,
починился ли разбор ЕГРН. На две тысячи должников такие проверки складываются в
реальные деньги, а на демонстрации у заказчика — в кончившийся баланс.

ПОЧЕМУ ВЫБОР НЕ ДЕЛАЕТ ОТЧЁТ ЛЖИВЫМ. Невыбранный источник не даёт результата
вовсе, и отчёт показывает его как «не опрашивался» — то самое состояние
:class:`~app.services.reporting.SourceStateCode.NOT_QUERIED`, которое уже
существует и уже означает «результата нет вовсе». Это главный инвариант проекта
(«не проверено» ≠ «ничего не найдено») применённый к новому поводу не спросить:
повод другой, а утверждение то же — мы не знаем.

Оценка взыскиваемости от этого не страдает: ``NOT_QUERIED`` не отвечен
(``answered=False``), значит бонусов за «чисто» по невыбранному источнику никто
не начислит.

ЧТО ЭТИМ НЕ ВЫКЛЮЧАЕТСЯ. Мост по телефону (depsearch) — он вне плана, и это
ровно то, о чём просил владелец: «которые не дипсерч». Без него проверка по
номеру невозможна вообще, у него свой поставщик и свой счёт, и выключать его
означало бы выключить вход в продукт.
"""

from __future__ import annotations

from collections.abc import Collection, Iterable
from dataclasses import dataclass

from app.domain.enums import ProviderName


@dataclass(frozen=True, slots=True)
class SourcePlan:
    """Выбор оператора на одну проверку.

    ``sources`` — ``None`` значит «все подключённые», и это поведение по
    умолчанию: проверка без выбора обязана остаться той же, какой была.
    Пустое множество — законный выбор «не спрашивать никого»: так смотрят, что
    даёт одна внутренняя база и мосты, не тратя ни рубля.

    ``buy_inn`` — покупать ли ИНН по паспорту. Флаг отдельный от списка
    источников, потому что мост не источник фактов: он ничего не находит, он
    добывает ВХОД для трёх источников, которые ищут только по ИНН. Выключенный,
    он оставляет их с честным «недостаточно данных: нужен ИНН» — бесплатно.
    """

    sources: frozenset[ProviderName] | None = None
    buy_inn: bool = True

    @classmethod
    def only(cls, names: Iterable[ProviderName], *, buy_inn: bool = True) -> SourcePlan:
        """План из перечисленных источников."""
        return cls(sources=frozenset(names), buy_inn=buy_inn)

    def includes(self, name: ProviderName) -> bool:
        """Спрашивать ли этот источник."""
        return self.sources is None or name in self.sources

    @property
    def is_selective(self) -> bool:
        """Отличается ли план от «спросить всё, что подключено».

        По этому признаку отчёт решает, говорить ли о выборе вслух. Сказать о
        нём обязательно: читатель, не знающий, что половину источников не
        спрашивали, прочитает отчёт как полный.
        """
        return self.sources is not None or not self.buy_inn

    def narrowed_to(self, configured: Collection[ProviderName]) -> list[ProviderName]:
        """Что этот план спросит из того, что подключено.

        Пересечение, а не сам выбор: выбранный, но неподключённый источник
        обещал бы ответ, которого не будет. Порядок — как у подключённых, чтобы
        перечисление в отчёте читалось одинаково от раза к разу.
        """
        return [name for name in configured if self.includes(name)]


#: Поведение по умолчанию и до появления выбора: спросить всё, купить ИНН.
EVERYTHING = SourcePlan()

__all__ = ["EVERYTHING", "SourcePlan"]
