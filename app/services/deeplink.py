"""Ссылки со страницы в бота: что можно передать в ``?start=`` и как это читать.

Зачем такие ссылки вообще. Веб-страницы этого продукта живут за подписанным
токеном и ничего не знают о том, кто их открыл: одну и ту же ссылку пересылают
юристу, приставу, начальнику. Значит на странице нельзя ставить кнопку, которая
ТРАТИТ деньги — проверка по реестрам платная, и каждый получатель ссылки
списывал бы баланс владельца кликами.

Поэтому кнопка со страницы уводит в бота, а платит уже бот: там человек
опознан, квота считается на него, а незнакомцу есть чем отказать.

Формат полезной нагрузки задан не нами. Telegram разрешает в ``?start=`` не
больше 64 символов и только ``[A-Za-z0-9_-]``: ни двоеточий, ни ФИО, ни
кириллицы. Отсюда «префикс плюс число».

Подписи здесь нет намеренно, и это не упущение. Подпись защищала бы от
подбора идентификатора должника — но подобрать его можно и без ссылки, просто
написав боту фамилию, а решает, отвечать ли, всё равно бот по его собственным
правилам доступа. Подпись создала бы вид защиты там, где её обеспечивает
другой слой.
"""

from __future__ import annotations

#: Префикс полезной нагрузки «проверить этого должника». Буквы, а не цифры:
#: голое число в ``?start=`` нельзя отличить от чего угодно другого, что мы
#: захотим передать ссылкой потом.
CHECK_PAYLOAD_PREFIX = "chk"

__all__ = ["CHECK_PAYLOAD_PREFIX", "debtor_id_from_payload"]


def debtor_id_from_payload(payload: str | None) -> int | None:
    """Идентификатор должника из ``?start=chk123``. ``None`` — не наша ссылка.

    Разбор строгий: всё, что не «префикс плюс цифры», отвергается молча.
    Полезная нагрузка приходит извне, её пишет кто угодно, и «почти похожее»
    здесь не значит ничего.
    """
    if not payload or not payload.startswith(CHECK_PAYLOAD_PREFIX):
        return None
    digits = payload[len(CHECK_PAYLOAD_PREFIX) :]
    return int(digits) if digits.isdigit() else None
