#: Бессрочная ссылка — решение владельца, и сказать об этом надо прямо: за одним
#: прогоном базы стоят десятки тысяч рублей, и «ограниченное время» здесь читалось
#: бы как «результат пропадёт».
LINK_FOREVER = "Ссылка бессрочная — отчёт не пропадёт и через год."
LINK_LIMITED = "Ссылка живёт {hours} ч с момента выдачи."


def help_text(container: Container, *, owner: bool) -> str:
    """Справка, собранная по текущему состоянию бота, а не по памяти.

    Три места здесь раньше были написаны словами и успели разойтись с ботом:
    перечень источников по ИНН (их стало вдвое больше), срок жизни ссылки (его
    отменили) и приглашение прогнать всю базу (прогон выключили). Теперь все
    три спрашивают настройку или реестр.
    """
    batch = container.settings.batch_enabled
    start = (HOW_TO_START_BATCH if batch else HOW_TO_START) if owner else HOW_TO_START_ALLOWED
    inn_only = view.inn_only_sources(container.registry.inn_only)
    blocks = [
        f"{container.settings.app_name} — как это работает",
        WHAT_IT_IS,
        start,
        WHAT_TO_ENTER_TEMPLATE.format(inn_only=inn_only or "источники, ищущие по ИНН"),
        WHY_BIRTH_DATE,
        WHAT_VERDICT_MEANS,
        WHAT_NUMBERS_MEAN,
        UNCHECKED_NOTE,
        f"{LIMITS_HEADER}\n{LIMITS}",
        LINKS_NOTE_TEMPLATE.format(lifetime=_link_lifetime(container)),
        commands_help(owner=owner, batch=batch),
    ]
    return "\n\n".join(blocks)


def _link_lifetime(container: Container) -> str:
    """Сколько живёт ссылка — по настройке, а не по тому, что было год назад."""
    hours = container.settings.share_link_ttl_hours
    return LINK_FOREVER if hours <= 0 else LINK_LIMITED.format(hours=hours)


async def send_help(message: Message, container: Container, user_id: int) -> None:
    """Справка и под ней меню.

    Принимает ``user_id``, а не готовый флаг владельца: меню собирается тем же
    ``menu_markup``, что и везде, а ему нужна ещё и ссылка на базу. Три
    вызывающих всё равно считали флаг из ``user_id`` прямо в аргументе.
    """
    owner = container.access_service.is_owner(user_id)
    chunks = split_message(help_text(container, owner=owner))
    markup = await menu_markup(container, user_id)
    for index, chunk in enumerate(chunks):
        # Меню — только под последним куском: клавиатура посреди справки
        # читается как её конец.
        last = index == len(chunks) - 1
        await message.answer(chunk, reply_markup=markup if last else None)


def build_router() -> Router:
    """Build this module's router.

    A factory rather than a module-level singleton: a Router can only be
    attached to one parent, so a shared instance would make a second
    Dispatcher — in tests, or in any future multi-bot setup — impossible.
    """
    router = Router(name="help")

    @router.message(Command("help"))
    async def handle_help(message: Message, container: Container, user_id: int) -> None:
        await send_help(message, container, user_id)

    @router.callback_query(F.data == HELP_CALLBACK)
    async def handle_help_callback(
        callback: CallbackQuery, container: Container, user_id: int
    ) -> None:
        await answer_callback(callback)
        message = callback_message(callback)
        if message:
            await send_help(message, container, user_id)

    return router
