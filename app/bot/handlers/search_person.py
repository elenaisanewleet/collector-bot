"""Свободный текст про должника: ловушка на весь чат.

Единственная задача модуля — поймать текст, присланный без единого нажатия, и
отдать его карточке запроса (:mod:`app.bot.handlers.query_card`). Раньше здесь
жил весь сценарий поиска по человеку, и модуль дважды переписывался целиком:
сначала пять вопросов подряд свернулись в одну строку, теперь строка перестала
быть запросом и стала пополнением карточки.

**Что изменилось по существу.** Прежний докстринг утверждал, что «перечитать
строку дешевле, чем держать частичный разбор». Это оказалось неверно ровно в том
месте, ради которого писалось: держать разбор было негде, поэтому «Иванова
Елена Николаевна» уходила в платную проверку сразу, а следующее сообщение «24 11
1994» перечитывалось как новая строка ни о ком — и оператор получал «а это к
чему вообще». Частичный разбор теперь есть, живёт в ``query_cards`` и стоит
одной строки в базе.

**Что не изменилось и не должно.** Роутер регистрируется в корне ПОСЛЕДНИМ и
только с ``StateFilter(None)``. Оба условия обязательны и оба остались
дословно: поиск по госномеру, VIN, адресу, договору и паспорту привязан к
состояниям, и без фильтра по пустому состоянию этот хэндлер съедал бы их ввод.
Карточка сознательно НЕ является состоянием FSM — иначе снять этот фильтр
пришлось бы, и четыре сценария сломались бы разом.
"""

from __future__ import annotations

from aiogram import F, Router
from aiogram.filters import StateFilter
from aiogram.types import Message

from app.bot.handlers import query_card
from app.container import Container


def build_free_text_router() -> Router:
    """Ловит строку, присланную без единого нажатия, — типичный случай.

    Только ``F.text``: документы остаются импорту, команды исключены явно.
    """
    router = Router(name="search_person_free_text")

    @router.message(StateFilter(None), F.text, ~F.text.startswith("/"))
    async def receive_free_line(message: Message, container: Container, user_id: int) -> None:
        await query_card.absorb(message, container, user_id)

    return router


__all__ = ["build_free_text_router"]
