DEMO_NOTE = "⚠️ Демо-режим: внешние источники заменены тестовыми данными, ответы вымышленные."


def sources_screen(container: Container, *, debtors: int) -> str:
    """Полный экран «Откуда данные» с живым состоянием каждого источника."""
    blocks = [HEADER, INTRO]
    if container.settings.is_demo:
        blocks.append(DEMO_NOTE)
    blocks.append(f"{INTERNAL_HEADER}\n{_internal_line(container, debtors)}\n{INTERNAL_BODY}")
    blocks.append(f"{EXTERNAL_HEADER}\n{EXTERNAL_INTRO}")
    blocks.extend(_external_blocks(container))
    bridge_block = _bridge_block(container)
    if bridge_block:
        blocks.append(bridge_block)
    blocks.append(f"{UNCHECKED_HEADER}\n{UNCHECKED_BODY}")
    blocks.append(f"{LIMITS_HEADER}\n{LIMITS}")
    return "\n\n".join(blocks)


def _external_blocks(container: Container) -> list[str]:
    blocks: list[str] = []
    for provider in container.registry.external:
        head = _state_line(_title(provider.name), provider.is_configured)
        note = SOURCE_NOTES.get(provider.name)
        blocks.append(f"{head}\n{note}" if note else head)
    return blocks


def _bridge_block(container: Container) -> str | None:
    """Мост «паспорт → ИНН» — отдельным блоком, а не строкой среди реестров.

    Он ничего не находит о должнике и в счёт «ответили N из M» не идёт; поданный
    как ещё один источник, он завысил бы и покрытие отчёта, и смету прогона.
    """
    bridge = container.registry.inn_bridge
    if bridge is None:
        return None
    return f"{_state_line(_title(bridge.name), bridge.is_configured)}\n{BRIDGE_NOTE}"


def _internal_line(container: Container, debtors: int) -> str:
    """Живое состояние внутреннего источника.

    У составного внутреннего провайдера нет ``is_configured``, и константная
    галочка здесь врала бы при пустой базе — а пустая база это ровно тот случай,
    когда оператор не понимает, почему ничего не находится.
    """
    title = f"{_title(ProviderName.INTERNAL)} (ваша 1С)"
    if debtors:
        noun = pluralize_ru(debtors, "запись", "записи", "записей")
        return f"✓ {title} — {CONNECTED_LABEL}: {debtors} {noun} в базе"
    if Path(container.settings.internal_csv_path).is_file():
        return f"✓ {title} — {CONNECTED_LABEL}: база пуста, читается стартовая выгрузка"
    return f"○ {title} — {NOT_CONFIGURED_LABEL}: база пуста, выгрузка не загружена (/import)"


def _state_line(title: str, configured: bool) -> str:
    mark = "✓" if configured else "○"
    state = CONNECTED_LABEL if configured else NOT_CONFIGURED_LABEL
    return f"{mark} {title} — {state}"


def _title(name: ProviderName) -> str:
    return PROVIDER_TITLES.get(name, name.value)


