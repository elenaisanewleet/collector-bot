"""Разметка сообщений бота — и защита от неё же.

Бот всю жизнь писал голым текстом: ``parse_mode=None`` выставлен глобально
(``app/main.py``), и это была не лень, а осознанная защита. Владелец назвал
результат прямо — «внешне бот очень выглядит серо», — и он прав: в карточке нет
ни одного акцента, вердикт и сумма иска набраны тем же кеглем, что и служебная
строка про Росреестр.

Чинится это не новым текстом, а разметкой уже написанного. Но включать её
«просто так» нельзя, и причина записана в самом коде (``app/bot/banner.py``):
**чужая фамилия с «<» уронит отправку сообщения**. В карточку едут имя из
чужой выгрузки, эхо разбора того, что оператор напечатал руками, адрес,
предмет исполнительного производства — всё это чужой текст, и любой «<» или
«&» в нём превратит сообщение в ошибку Telegram. Молчащий бот хуже серого.

Поэтому здесь два слоя, и нужны оба:

*   :func:`esc` экранирует КАЖДУЮ подставляемую величину. Правило простое и без
    исключений: постоянный текст пишется с тегами, любая переменная проходит
    через ``esc``;
*   :func:`strip_tags` разбирает разметку обратно. Он нужен на случай, если
    первый слой всё-таки где-то пропущен: отправка падает, и карточка уходит
    простым текстом вместо того, чтобы не уйти вовсе.

Второй слой — не перестраховка ради перестраховки. Экранирование живёт в
десятке мест, и достаточно одной новой строки без ``esc``, чтобы карточка
перестала доходить до владельца. Ошибка в оформлении не имеет права стоить
человеку результата проверки, за которую заплачено.
"""

from __future__ import annotations

import re
from html import escape

#: Разметка, которую понимает Telegram и используем мы. Полужирный — и всё:
#: курсив в чате читается хуже прямого, а моноширинный превращает строку в код.
#: Список намеренно короткий — :func:`strip_tags` обязан знать его целиком.
_TAG_PATTERN = re.compile(r"</?b>")

HTML = "HTML"


def esc(value: str) -> str:
    """Чужой текст, готовый встать внутрь размеченной строки.

    Через неё проходит всё, что пришло не от нас: имя должника, эхо разбора,
    адрес, предмет производства, название компании. Пропустить здесь величину
    значит получить не кривую вёрстку, а несостоявшуюся отправку.
    """
    return escape(value, quote=False)


def bold(value: str) -> str:
    """Полужирный. Величину внутрь передавать уже экранированной."""
    return f"<b>{value}</b>"


def strip_tags(text: str) -> str:
    """Та же строка без разметки — для отправки простым текстом.

    Нужна там, где Telegram отверг размеченное сообщение: экранирование
    где-то пропущено, и единственное, что ещё можно спасти, — это сам текст.
    Сущности разворачиваются обратно, иначе в запасном сообщении осталось бы
    «&amp;» вместо «&».
    """
    return _unescape(_TAG_PATTERN.sub("", text))


def _unescape(text: str) -> str:
    # Ровно обратное :func:`esc`, и в обратном порядке: «&amp;lt;» обязано
    # развернуться в «&lt;», а не в «<».
    return text.replace("&lt;", "<").replace("&gt;", ">").replace("&amp;", "&")


__all__ = ["HTML", "bold", "esc", "strip_tags"]
