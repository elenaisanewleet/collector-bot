class PhoneNameResult(ProviderResult):
    """``ProviderResult`` моста плюс само имя.

    Как и у моста «паспорт → ИНН», поле живёт только в памяти одного прогона:
    в ``search_results`` оно не пишется и из кэша не восстанавливается. На
    кэш-хите имя берётся из сохранённого субъекта.
    """

    name: PersonName | None = None
    birth_date: Any = None
    #: ИНН и паспорт, если поставщик их отдал. Оба необязательны и оба сильно
    #: экономят: с готовым ИНН мост «паспорт → ИНН» не сработает вовсе (он
    #: проверяет ``is_needed``), а это минус одно платное обращение с каждого
    #: должника и охват всех, а не только тех, у кого паспорт есть в выгрузке.
    #:
    #: Как и имя, живут в памяти одного прогона: в ``search_results`` не
    #: пишутся, на кэш-хите берутся из сохранённого субъекта.
    inn: str | None = None
    passport: str | None = None
    #: СНИЛС. В отличие от ИНН и паспорта он ничего не экономит: по нему не
    #: ищет ни один источник и ни один мост его не спрашивает. Он здесь потому,
    #: что нужен владельцу в заявлении, а приходит тем же ответом — не взять
    #: его значит заставить искать документ отдельно и вручную.
    snils: str | None = None
    #: Дата выдачи паспорта. Тоже не ключ поиска: ФНС ищет ИНН по серии и
    #: номеру и даты не спрашивает (см. ``identity_bridge.missing_input_for``).
    #: Нужна там же, где СНИЛС, — в заявлении, где паспорт указывают полностью.
    #: ``Any``, а не ``date``, по той же причине, что и ``birth_date``:
    #: ``ProviderResult`` не знает про домен.
    passport_issued: Any = None
    #: Адрес. Единственное поле здесь, которое открывает ещё один источник:
    #: ЕГРН ищет объект по адресу, и без адреса он молчит. Требование к адресу
    #: жёсткое: только адрес с квартирой примет Росреестр — см.
    #: :func:`_address_candidates` и :func:`~app.utils.address.pick_address`.
    address: str | None = None
    #: ВСЕ адреса-кандидаты, а не только выбранный.
    #:
    #: Заведено после четвёртой неудачной попытки выбрать правильный кодом.
    #: Живой ответ по одному номеру: ``address_variants=8``, и опорный блок —
    #: тот, из которого взяты паспорт, СНИЛС и дата рождения, — несёт ОДИН
    #: адрес, и это не тот, где должник живёт. Признака, по которому машина
    #: отличила бы верный адрес от семи прочих, в ответе нет: ни частота, ни
    #: порядок выдачи, ни богатство блока таким признаком не оказались.
    #:
    #: Зато он есть у оператора — он знает своего должника. Поэтому кандидаты
    #: доезжают до карточки целиком, и выбор предлагается человеку. Это не
    #: отказ от автоматики: выбранный по умолчанию остаётся, и на массовом
    #: прогоне работает он. Но там, где решение стоит платного запроса в
    #: Росреестр и попадания в исковое заявление, последнее слово за человеком.
    address_options: tuple[str, ...] = ()


class PhoneNameProvider(BaseProvider):
    """Телефон → ФИО через настраиваемый эндпоинт.

    Политика «звать или нет» живёт здесь целиком: сервис поиска спрашивает
    :meth:`is_needed` и больше ничего не решает.
    """

    name = ProviderName.PHONE_BRIDGE
    title = PROVIDER_TITLES[ProviderName.PHONE_BRIDGE]

    def __init__(self, settings: Settings, client: VendorJsonClient | None = None) -> None:
        self._settings = settings
        self._client = client

    @property
    def is_configured(self) -> bool:
        return self._settings.phone_bridge_configured

    def _vendor_client(self) -> VendorJsonClient:
        if self._client is None:
            self._client = VendorJsonClient(
                VendorConfig(
                    base_url=self._settings.phone_bridge_base_url,
                    path=self._settings.phone_bridge_path,
                    auth_style=self._settings.phone_bridge_auth_style,
                    auth_name=self._settings.phone_bridge_auth_name,
                    api_key=self._settings.phone_bridge_api_key,
                    field_map_path=self._settings.phone_bridge_field_map,
                ),
                timeout_seconds=self._settings.request_timeout_seconds,
                retry=RetryPolicy(
                    max_retries=self._settings.provider_max_retries,
                    backoff_seconds=self._settings.provider_retry_backoff_seconds,
                ),
                provider_label=self.name.value,
            )
        return self._client

    def is_needed(self, subject: SearchSubject) -> bool:
        """Нужен ли мост этому субъекту.

        Только когда имени нет, а номер есть. Если оператор уже назвал ФИО —
        своё имя сильнее чужого, и переводить номер незачем.
        """
        return subject.name is None and bool(subject.phone)

    def will_query(self, subject: SearchSubject) -> bool:
        """Дойдёт ли дело до обращения. Нужно смете массового прогона."""
        return self.is_configured and self.is_needed(subject)

    def missing_input_for(self, subject: SearchSubject) -> tuple[MissingInput, ...]:
        return () if subject.phone else (MissingInput.PHONE,)

    async def _fetch(self, subject: SearchSubject) -> ProviderResult:
        missing = self.missing_input_for(subject)
        if missing or not subject.phone:
            return self.insufficient_query("Нужен номер телефона", missing=missing)
        records, _raw = await self._vendor_client().fetch_records({"phone": subject.phone})
        return _read_rows(records, phone=subject.phone, provider=self)


def _individual_inn(raw: object) -> str | None:
    """ИНН ФИЗЛИЦА — двенадцать цифр, и только он.

    Десятизначный ИНН принадлежит юрлицу. Три источника, ради которых ИНН и
    добывается, ищут по ``innfiz`` и валидируют его как двенадцать знаков:
    десятизначный будет отклонён, но вызов всё равно оплачен. Молча пропустить
    его — значит купить три гарантированно пустых ответа на каждом должнике.
    """
    if not raw:
        return None
    value = normalize_inn(str(raw))
    return value if value and len(value) == INN_INDIVIDUAL_LENGTH else None


def _read_rows(
    rows: list[RecordDict], *, phone: str, provider: PhoneNameProvider
) -> ProviderResult:
    """Собрать личность из ответа поставщика.

    Поставщик отвечает не записью о человеке, а свалкой находок: сорок с лишним
    строк из разных утечек, где половина про доставку еды, а личность разложена
    по нескольким блокам. Форма при этом устойчива — владелица сформулировала
    это дословно: «названия полей и где в каком блоке, для каждого номера это
    всё идентично». На живом ответе так и есть, и разбор построен на этом.

    ТРИ ШАГА, И СРЕДНИЙ — САМЫЙ ВАЖНЫЙ.

    1. **Якорь.** Ищется блок, где признаков личности больше всего: ФИО, дата
       рождения, паспорт, СНИЛС, ИНН в одной записи. На живом ответе это
       единственный блок с четырьмя из пяти, и он же несёт кириллическое ФИО.
       Раньше якорем была ПЕРВАЯ строка с читаемым именем — на том же ответе ею
       оказывалась строка из иностранной утечки, где кроме латинского имени нет
       ничего.

    2. **Родня.** К якорю добираются только те блоки, которые с ним связаны
       общим идентификатором: тем же паспортом, тем же СНИЛСом или тем же ФИО.
       Это единственное место, где разбор мог соврать дорого, и вот чем.
       Находки в ответе объединяет ОДИН ТОЛЬКО НОМЕР ТЕЛЕФОНА, а номером
       пользуются и родственники, и прежние владельцы номера: на живом ответе
       рядом с владелицей лежат ещё три человека с другими ФИО. Разбор, который
       добирал недостающее «по всему ответу», однажды взял бы дату рождения
       одного человека к паспорту другого — и собрал бы личность, которой не
       существует. Проверить это по отчёту нельзя: он выглядел бы обычно.

       Связь именно по идентификатору, а не по соседству: на живом ответе ИНН
       лежит отдельным блоком без имени, но с тем же паспортом, что у якоря, —
       и это проверяемое «тот же человек», а не догадка.

    3. **Годность.** Внутри родни берётся первое ПРИГОДНОЕ значение, и каждая
       проверка снята с живого ответа:

       * ИНН — только двенадцать знаков. Десять принадлежат ЮРЛИЦУ: на живом
         ответе такой пришёл из строки почтовой доставки, где рядом стоит
         отправитель-ООО. За ним ушли бы три платных запроса про чужую компанию
         (:func:`_individual_inn`);
       * паспорт — только десять цифр. В том же ответе лежат документы на семь
         и девять цифр (иностранный и загран). Паспорт едет дальше в ФНС за
         ИНН, и негодный — это оплаченный пустой ответ;
       * СНИЛС — с контрольной суммой (:func:`_read_snils`).

    ГЛАВНОЕ ПРАВИЛО ОСТАЁТСЯ. Даже собранная так личность — гипотеза, а не
    запись реестра. Поэтому имя отсюда остаётся ключом поиска, записей мост не
    приносит, а на странице проверок под таблицей написано, что документы не
    подтверждены и перед подачей их надо сверить.
    """
    name, anchor = _pick_anchor(rows)
    if name is None:
        return PhoneNameResult(
            provider=provider.name,
            status=ProviderStatus.NO_RESULTS,
            records=(),
            name=None,
            note=f"По номеру {mask_phone(phone)} имя не определено",
        )

    kin, rejected = _kin(rows, anchor)
    passport = _pick(kin, _read_passport, "passport", "passport_number")
    # Кандидаты считаются ОДИН раз: и выбор по умолчанию, и список для
    # оператора обязаны говорить об одном и том же ответе.
    front, rest = _address_candidates(kin, anchor)
    # ОДНО МЕСТО — ОДНА СТРОКА, и в карточке она та же, что в списке выбора.
    #
    # Правило владельца решает МЕСТО — из какой утечки брать адрес. Написание
    # того же места — отдельный вопрос: поставщик присылает его несколькими
    # («обл. Тестовая…» и «обл Тестовая…»), и выбирается одно из присланных, то,
    # что проходит в ЕГРН (см. ``app.utils.address``). Выбор адреса и список
    # считаются разными правилами, поэтому написание согласуется здесь — иначе
    # оператор увидел бы список без единой галочки и решил бы, что адрес не
    # выбран вовсе.
    chosen = _address_by_origin(kin, name)
    options = address_options(rest, preferred=front, chosen=chosen)
    if chosen is not None:
        chosen = as_offered(chosen, options) or chosen
    result = PhoneNameResult(
        provider=provider.name,
        status=ProviderStatus.SUCCESS,
        records=(),
        name=name,
        birth_date=_pick(kin, _read_day, *_field_keys()["birth_date"]),
        inn=_pick(kin, _individual_inn, "inn", "innfiz"),
        passport=passport,
        snils=_pick(kin, _read_snils, "snils"),
        passport_issued=_issue_date(kin, passport),
        # ПО ПРАВИЛУ ВЛАДЕЛЬЦА: сначала утечка, потом порядок, потом частота.
        # ``_address_by_origin`` заменил четыре правила, ни одно из которых
        # не могло работать: признак верного адреса лежит в происхождении
        # блока, а карта полей ключи ``data`` и ``source`` отбрасывала.
        address=chosen,
        address_options=tuple(options),
        note=f"ФИО определено по номеру {mask_phone(phone)}",
    )
    # ЧТО РАЗОБРАЛОСЬ, А ЧТО НЕТ — списком имён полей, без значений.
    #
    # Строка появилась после первого же вопроса, на который нечем было
    # ответить: «адрес в итоге забирает?». По одному отчёту это не различить —
    # раздел ЕГРН пишет «недостаточно данных» и когда адреса не было в ответе
    # поставщика, и когда он там был, а разбор его не нашёл. Первое — не наша
    # беда, второе — наша, и лечатся они противоположным.
    #
    # Значения не печатаются: имён полей хватает, чтобы отличить одно от
    # другого, а лог живёт дольше и расходится шире, чем отчёт.
    fields = ("birth_date", "inn", "passport", "snils", "passport_issued", "address")
    found = sorted(field for field in fields if getattr(result, field) is not None)
    shapes = _shapes(kin, fields, found)
    logger.info(
        "phone_bridge.parsed",
        rows=len(rows),
        kin=len(kin),
        found=found,
        # ЧТО ПОСТАВЩИК ВООБЩЕ ПРИСЛАЛ — именами ключей, когда что-то не
        # разобралось. Без этого «дата рождения не пришла» и «пришла под именем,
        # которого нет в нашем списке» выглядят одинаково: пустым полем. Первое
        # не наша беда, второе — наша, и стоит одной строки в таблице синонимов.
        #
        # Ровно так это и всплыло: владелец сказал «там должна быть моя дата
        # рождения в ответе, почему мы её не взяли», а ответить было нечем.
        # Для адреса синонимов шесть, для даты рождения было два.
        #
        # Только ИМЕНА. Значения в лог не идут никогда: он живёт дольше отчёта и
        # расходится шире.
        keys=sorted({key for row in kin for key in row}) if len(found) < len(fields) else [],
        # А ЭТО — ФОРМА ЗНАЧЕНИЯ, и она понадобилась на следующем же шаге.
        # Живой ответ показал ``birth_date`` среди присланных ключей, то есть
        # ровно под тем именем, которое мы и читаем: имя подошло, а значение
        # разбор отверг. «Пришло пустым» и «пришло в формате, которого мы не
        # ждём» снова выглядели одинаково, и снова лечатся противоположным.
        #
        # Печатается ШАБЛОН, а не значение: цифры заменены девятками, буквы —
        # латинской A, разделители оставлены как есть. «9999-99-99» и
        # «99.99.9999» называют формат точно и не говорят о человеке ничего.
        shapes=shapes,
        # И ПРЯМОЙ ВЫВОД, потому что три списка выше приходится сверять между
        # собой, а вывод из них каждый раз один и тот же. Поле здесь, когда
        # ключ в ответе ЕСТЬ, а непустого значения нет ни в одном блоке: то
        # есть поставщик про этого человека поля не знает, и чинить нечего.
        #
        # Расшифровывать «found без birth_date, но birth_date в keys, и shapes
        # пустой» пришлось трижды. На третий раз дешевле написать словами.
        empty=_absent(fields, found, shapes),
        # ОТКУДА ВЗЯТ АДРЕС. Он единственный открывает платный источник, и
        # правило его выбора переписывалось трижды — каждый раз по отчёту, то
        # есть вслепую. Имя ключа и число вариантов различают три разные беды,
        # которые в отчёте выглядят одинаково: адрес не в опорном блоке; опорный
        # блок опознан не тот; в блоке два адреса и выбран не тот ключ.
        **_address_choice(kin, anchor, result.address),
        # СКОЛЬКО БЛОКОВ ОТВЕРГНУТО, ПО КАКОМУ ПРИЗНАКУ И ЧТО В НИХ БЫЛО.
        # Отбраковка — главная защита разбора и его же главная слепая зона:
        # выброшенный блок неотличим от блока, которого поставщик не присылал.
        # ``dropped_carried`` эту слепоту и снимает — см. :func:`_rejection_report`.
        **_rejection_report(rejected),
    )
    return result


#: Сколько букв шаблона хватает, чтобы узнать формат. Дата — десять, ИНН —
#: двенадцать; всё, что длиннее, это адрес или ФИО, и там формат не разбирают.
MAX_SHAPE = 24


def _field_keys() -> dict[str, tuple[str, ...]]:
    """Под какими ключами лежит каждое поле ответа поставщика.

    Функция, а не модульная константа, по той же причине, что и список в
    :func:`_marks`: ``_ADDRESS_KEYS`` объявлен ниже по файлу, и константа упала
    бы при импорте. Тело же вычисляется при вызове, когда объявлено всё.

    Один источник правды на ЧЕТЫРЁХ потребителей: разбор поля, выбор якоря,
    сверку блоков на противоречие и диагностику. До этой правки список синонимов
    лежал в каждом из четырёх мест своей копией — и стоило это ровно того, чего
    и должно было: живой ответ прислал дату рождения под ключом ``bday``,
    которого не было ни в одной копии, и бот сообщил «дату рождения поставщик не
    знает» про человека, у которого она в ответе есть.

    Добавить синоним в одно место и забыть про три — та же беда с отсрочкой:
    разбор бы дату взял, а сверка блоков на противоречие её бы не увидела и
    пустила бы к якорю блок с ЧУЖОЙ датой рождения.
    """
    return {
        # ``bday`` подтверждён живым ответом: блок из утечки банка несёт
        # ``bday``, ``phone`` и ``name`` заглавными, а соседний блок — тот же
        # ``birth_date``, но пустым.
        "birth_date": ("birth_date", "bday", "dob"),
        "inn": ("inn", "innfiz"),
        "passport": ("passport", "passport_number"),
        "snils": ("snils",),
        "fio": ("fio", "full_name", "name"),
        "address": _ADDRESS_KEYS,
        # ОТКУДА БЛОК. Не идентификатор и не факт — но именно он решает, какой
        # из восьми адресов настоящий. Владелец назвал порядок по утечкам:
        # госуслуги, затем медицинская база, затем остальное. Кода, способного
        # выбрать верный адрес без этого признака, не существует — проверено
        # четырьмя правилами подряд (см. :data:`_SOURCE_RANK`).
        "origin": _ORIGIN_KEYS,
    }


#: Что личность НЕ опознаёт. Адрес — это место, а не человек: блок с одним
#: адресом якорем быть не должен. Происхождение — имя утечки, и в общей таблице
#: оно стоит по делу (им решается адрес), но про человека не говорит ничего.
_NOT_IDENTITY = frozenset({"address", "origin"})


def _identity_marks(row: RecordDict) -> int:
    """Сколько признаков ЛИЧНОСТИ в одной записи — ФАКТОВ, а не ключей.

    По этому числу выбирается якорь: блок, где признаки стоят вместе, — это
    человек, а не обрывок чужой утечки.

    СЧИТАЮТСЯ ФАКТЫ, И ОБЕ ОШИБКИ ЗДЕСЬ БЫЛИ. Считались ключи, а у одного
    факта их несколько: дата рождения приезжает как ``birth_date``, ``bday`` и
    ``dob``, и блок, несущий два её написания, выглядел богаче блока с
    паспортом. Хуже того, в подсчёт попало ПРОИСХОЖДЕНИЕ блока: ключи ``data``
    и ``source`` добавились в общую таблицу ради выбора адреса, а сюда
    приехали заодно — и блок, у которого заполнены оба, обгонял блок с
    паспортом, ничего о человеке не сообщив.

    Стоит это дорого и не сразу видно: якорь — это «чей это паспорт», а на нём
    же держится отбраковка родни. Ошибись якорем — и блок с настоящими
    документами уйдёт как «противоречащий».
    """
    return sum(
        1
        for field, keys in _field_keys().items()
        if field not in _NOT_IDENTITY and _first(row, *keys) is not None
    )


def _shapes(kin: list[RecordDict], fields: tuple[str, ...], found: list[str]) -> dict[str, str]:
    """Форма первого непустого значения — для полей, которые не разобрались.

    Только для неразобравшихся: у остальных форма ничего не объясняет, а лог
    ради неё становится вдвое длиннее.
    """
    field_keys = _field_keys()
    shapes: dict[str, str] = {}
    for field in fields:
        if field in found:
            continue
        keys = field_keys.get(field)
        if keys is None:
            continue
        for row in kin:
            raw = _first(row, *keys)
            if raw is not None:
                shapes[field] = _shape(raw)
                break
    return shapes


def _absent(fields: tuple[str, ...], found: list[str], shapes: dict[str, str]) -> list[str]:
    """Поля, у которых ключ в ответе есть, а непустого значения нет нигде.

    Прямой вывод вместо сверки трёх списков. «Поставщик не знает» и «мы не
    поняли формат» лечатся противоположным, а в логе различались только
    пересечением ``found``, ``keys`` и ``shapes`` — расшифровывать это вручную
    пришлось трижды, прежде чем стало ясно, что дешевле написать словами.

    Поле без таблицы ключей сюда не попадает: про него разбор ничего не
    спрашивал, и «пришло пустым» про него — не утверждение, а домысел.
    """
    field_keys = _field_keys()
    return sorted(
        field
        for field in fields
        if field not in found and field not in shapes and field in field_keys
    )


def _shape(raw: object) -> str:
    """Шаблон значения: цифры — девятки, буквы — A, остальное как есть.

    Значение в лог не попадает ни при каких условиях. Нечто, что не строка
    вовсе (объект, список, число), называется своим типом: это тоже ответ, и
    иногда единственно нужный — ``str(dict)`` разбирается в мусор, а выглядит
    как непонятый формат.
    """
    if not isinstance(raw, str):
        return type(raw).__name__
    pattern = "".join("9" if ch.isdigit() else "A" if ch.isalpha() else ch for ch in raw)
    return pattern[:MAX_SHAPE] + ("…" if len(pattern) > MAX_SHAPE else "")


#: Кириллическое слово. Требование не про язык, а про пригодность ключа: искать
#: в русской выгрузке транслитерацией — то же самое, что не искать.
_CYRILLIC = re.compile(r"[А-Яа-яЁё]")


def _pick_anchor(rows: list[RecordDict]) -> tuple[PersonName | None, RecordDict | None]:
    """Блок, вокруг которого собирается личность, и разобранное из него имя.

    Выбирается по числу признаков личности в одной записи, а не по порядку в
    ответе. Владелица описала это правило дословно: «названия полей и где в
    каком блоке, для каждого номера это всё идентично» — форма ответа
    устойчива, и личность в ней лежит одним блоком, где ФИО, дата рождения,
    паспорт и СНИЛС стоят вместе.

    Раньше якорем была ПЕРВАЯ запись с читаемым именем. На живом ответе ею
    оказывалась запись из иностранной утечки, где кроме латинского имени нет
    ничего, — а настоящий блок с четырьмя признаками лежал шестым.

    Кириллица предпочтительнее латиницы, и это не про язык: искать в русской
    выгрузке транслитерацией всё равно что не искать. Но обязательной её
    сделать нельзя — если поставщик отдал только транслитерацию, честное «в
    выгрузке не найден» лучше молчания.

    Разбор имени строгий: то, что не читается как ФИО, не собирается по кускам,
    потому что полусобранное поднимет чужую строку.

    ПРИ РАВЕНСТВЕ ПРИЗНАКОВ РЕШАЕТ УТЕЧКА, а не порядок в ответе. Правило
    владельца («госуслуги, затем медицинская база, затем остальное») проверено
    живьём на адресах, и здесь оно про то же: чей это блок. Порядок остаётся
    последним доводом, но именно он однажды и подвёл — ответ по одному номеру
    пришёл на три блока короче, порядок сместился, якорем стал блок без
    паспорта и без адреса, и вместе с ним отбраковка выбросила три блока по
    дате рождения. Одна и та же проверка двумя днями подряд дала разный ответ,
    хотя код не менялся.
    """
    best: tuple[tuple[int, int, int, int], PersonName, RecordDict] | None = None
    for order, row in enumerate(rows):
        raw = _first(row, "fio", "full_name", "name")
        if not raw:
            continue
        try:
            parsed = parse_fio(str(raw))
        except NameParseError:
            continue
        # Ключ сравнения: кириллица, число признаков личности, доверие к
        # утечке, порядок в ответе. Минус у порядка и у ранга утечки — чтобы
        # при равенстве побеждали первый и самая доверенная.
        rank = (
            1 if _CYRILLIC.search(str(raw)) else 0,
            _identity_marks(row),
            -_origin_rank(row),
            -order,
        )
        if best is None or rank > best[0]:
            best = (rank, parsed, row)
    return (best[1], best[2]) if best is not None else (None, None)


def _marks(row: RecordDict) -> dict[str, object]:
    """Годные идентификаторы одной записи. Негодные не попадают сюда вовсе.

    Проверка обязательна и не формальна: в живом ответе поле ``inn`` несёт
    одиннадцать цифр (это СНИЛС, а не ИНН), а ``passport`` — то семь цифр, то
    девять. Негодное значение не должно ни приниматься, ни служить поводом
    отвергнуть чужой блок: мусор не идентифицирует никого.

    Ключи берутся из :func:`_field_keys` — той же таблицы, по которой поля и
    разбираются. Своя копия здесь была опаснее прочих: синоним, известный
    разбору и неизвестный этой сверке, пустил бы к якорю блок с чужой датой
    рождения, и личность собралась бы из двух разных людей.
    """
    keys_by_field = _field_keys()
    readers: tuple[tuple[str, Callable[[object], object | None]], ...] = (
        ("passport", _read_passport),
        ("snils", _read_snils),
        ("birth_date", _read_day),
        ("fio", _read_fio_mark),
    )
    found: dict[str, object] = {}
    for kind, read in readers:
        raw = _first(row, *keys_by_field[kind])
        if raw is not None and (value := read(raw)) is not None:
            found[kind] = value
    return found


#: Адрес годится для ЕГРН, только если доходит до помещения. Проверено живьём:
#: по адресу до дома Росреестр отвечает ошибкой, и вызов всё равно оплачен.
#: Список полей — все, под которыми поставщик присылает адрес.
_ADDRESS_KEYS = (
    "address",
    "address_reg",
    "permanent_registration_address",
    "actual_residence_address",
    "address_fact",
    "residence",
)


#: Под какими ключами блок называет свою утечку.
_ORIGIN_KEYS = ("data", "source")

#: ПОРЯДОК ДОВЕРИЯ К УТЕЧКАМ, заданный владельцем дословно: «где есть
#: governmentservices — с этого блока берём в приоритете, если нет — ищем
#: mosgorzdrav_2025 или mosgorzdrav, и в третью очередь grastin_2021_2022».
#:
#: ЭТО ТОТ ПРИЗНАК, КОТОРОГО НЕ ХВАТАЛО. Четыре правила подряд выбрали неверный
#: адрес на живом ответе с восемью кандидатами — первый с квартирой, частота по
#: родне, опорный блок, опорный блок с предпочтением квартире. Ни одно не могло
#: сработать: в самом ответе нет ничего, что отличало бы верный адрес от семи
#: прочих. Кроме происхождения блока — и его владелец знает, а код не знал,
#: потому что карта полей ключи ``data`` и ``source`` отбрасывала.
#:
#: Порядок осмысленный, а не вкусовой: госуслуги ведут адрес регистрации по
#: заявлению самого человека, медицинская база — по его последнему приёму, а
#: маркетинговая выгрузка 2021–2022 годов устарела на годы.
_SOURCE_RANK: dict[str, int] = {
    "governmentservices": 0,
    "mosgorzdrav_2025": 1,
    "mosgorzdrav": 1,
    "grastin_2021_2022": 2,
}

#: Хуже любой известной утечки, но не «нельзя брать»: неизвестный источник
#: участвует в общем порядке выдачи, как и раньше.
_UNRANKED = len(_SOURCE_RANK) + 1


def _origin_rank(row: RecordDict) -> int:
    """Насколько доверяем утечке этого блока. Меньше — больше доверия.

    Берётся ЛУЧШИЙ из ключей: один и тот же блок несёт ``source`` и ``data``
    («mosgorzdrav_2025» и «mosgorzdrav»), и требовать совпадения обоих значило
    бы зависеть от того, какой ключ поставщик заполнил в этот раз.
    """
    ranks = [
        _SOURCE_RANK.get(" ".join(str(raw).split()).lower(), _UNRANKED)
        for key in _ORIGIN_KEYS
        if (raw := row.get(key))
    ]
    return min(ranks, default=_UNRANKED)


def _names_the_person(row: RecordDict, name: PersonName) -> bool:
    """Назван ли в блоке НАШ человек — терпимо к записи имени.

    Требование владельца: «везде должно быть указано ФИО либо латиницей, либо
    вот как тут в разных вариантах». Живой ответ показывает три записи одного
    имени в трёх блоках: «Клочкова klochkova Елена elena Николаевна» (кириллица
    и транслит вперемешку в одном поле), «Klochkova Elena» (только транслит) и
    «Клочкова Елена Николаевна».

    Поэтому сравниваются не строки, а МНОЖЕСТВА слов, приведённых к латинице:
    фамилия и имя должны найтись среди слов блока. Отчество не требуется — в
    двух из трёх живых блоков его нет вовсе.

    Зачем это нужно вообще: приоритет утечки применяется только к блокам про
    нашего человека. Блок с адресом и без имени — а таких в ответе большинство
    — не имеет права победить по одному лишь имени утечки: номером телефона
    пользуются родственники и прежние владельцы номера.
    """
    words = {
        translit_ru(part)
        for key in _field_keys()["fio"]
        if (raw := row.get(key))
        for part in str(raw).split()
    }
    words.discard("")
    needed = {translit_ru(name.last_name), translit_ru(name.first_name)}
    return needed <= words


def _address_by_origin(kin: list[RecordDict], name: PersonName | None) -> str | None:
    """Адрес по правилу владельца: сначала утечка, потом порядок, потом частота.

    Порядок ровно тот, который он задал, и каждый шаг делается только когда
    предыдущий не дал ничего:

    1. блоки самой доверенной утечки, где назван наш человек;
    2. следующая утечка, и так по :data:`_SOURCE_RANK`;
    3. первый блок с нашим ФИО, у которого адрес вообще есть;
    4. частота адресов среди блоков с нашим ФИО;
    5. то же по всей родне — если имени нет ни в одном блоке.

    ДВА ПРОХОДА ПО УТЕЧКАМ, и это единственное, что я добавил к правилу.
    Сначала в каждой группе ищется адрес С КВАРТИРОЙ, и лишь если ни в одной
    группе такого нет — любой. Причина не вкусовая: адрес до дома не открывает
    ЕГРН вовсе (Росреестр отвечает ошибкой за уже списанные деньги), то есть
    «самый доверенный, но без квартиры» не работает ни для чего. Порядок утечек
    при этом не нарушен — он решает внутри каждого прохода.
    """
    named = [row for row in kin if name is not None and _names_the_person(row, name)]
    pool = named or kin
    groups = sorted({_origin_rank(row) for row in pool} - {_UNRANKED})
    for premises_only in (True, False):
        for rank in groups:
            rows = [row for row in pool if _origin_rank(row) == rank]
            chosen = _first_address(rows, premises_only=premises_only)
            if chosen is not None:
                return chosen
    # Ни одной известной утечки: первый блок с адресом, потом частота.
    for row in pool:
        chosen = _first_address([row], premises_only=True)
        if chosen is not None:
            return chosen
    front, rest = _address_candidates(pool, None)
    return pick_address(rest, preferred=front)


def _first_address(rows: list[RecordDict], *, premises_only: bool) -> str | None:
    """Лучший адрес этой группы блоков, в порядке выдачи."""
    _, candidates = _address_candidates(rows, None)
    if premises_only:
        candidates = [item for item in candidates if has_premises(item)]
    return pick_address(candidates)


def _address_candidates(
    kin: list[RecordDict], anchor: RecordDict | None
) -> tuple[list[str], list[str]]:
    """Адреса опорного блока и адреса остальной родни, двумя списками.

    Одно место, где решается, ЧТО считается кандидатом: и выбор по умолчанию, и
    список для оператора берут кандидатов отсюда. Второй проход по тем же
    ключам разошёлся бы с первым на первой же правке — ровно так уже вышло с
    правилом «доходит ли адрес до квартиры», жившим тремя копиями.
    """
    front = [str(raw) for key in _ADDRESS_KEYS if anchor is not None and (raw := anchor.get(key))]
    rest = [
        str(raw)
        for row in kin
        if row is not anchor
        for key in _ADDRESS_KEYS
        if (raw := row.get(key))
    ]
    return front, rest


def _address_choice(
    kin: list[RecordDict], anchor: RecordDict | None, chosen: str | None
) -> dict[str, object]:
    """Откуда взят адрес — ИМЕНАМИ КЛЮЧЕЙ И ЧИСЛАМИ, без единого значения.

    Заведено потому, что по отчёту правило выбора не отладить. Владелец трижды
    показывал неверный адрес, и каждый раз оставалось гадать: то ли адрес лежит
    не в опорном блоке, то ли опорный блок опознан не тот, то ли в одном блоке
    два адреса и выбран не тот ключ. Три разные починки — и ни одного способа
    отличить их друг от друга.

    Значений здесь нет и быть не может: лог живёт дольше отчёта и расходится
    шире, а адрес — это персональные данные. Имени ключа хватает, чтобы решить,
    какое правило неверно.
    """
    if chosen is None:
        return {}
    # Сравнение ПО МЕСТУ, а не по строке: в карточку уходит одно написание из
    # присланных, и оно не обязано совпадать посимвольно с тем блоком, из
    # которого адрес взят («обл. Тестовая…» против «обл Тестовая…»). Сравнивай
    # строки — и диагностика, ради которой всё это и завелось, писала бы
    # «address_from=none:none» ровно там, где адрес найден.
    where = "none"
    key_name = "none"
    for label, rows in (("anchor", [anchor] if anchor else []), ("kin", kin)):
        for row in rows:
            for key in _ADDRESS_KEYS:
                raw = row.get(key)
                if raw is not None and is_same_place(str(raw), chosen):
                    where, key_name = label, key
                    break
            if key_name != "none":
                break
        if key_name != "none":
            break
    # МЕСТ, а не строк: их число сравнивают с длиной списка выбора, и одно
    # место, записанное поставщиком трижды, там одна строка.
    distinct = {
        same_place(str(raw)) for row in kin for key in _ADDRESS_KEYS if (raw := row.get(key))
    }
    return {
        "address_from": f"{where}:{key_name}",
        "address_variants": len(distinct),
        "anchor_address_keys": sorted(
            key for key in _ADDRESS_KEYS if anchor is not None and anchor.get(key)
        ),
    }


def _read_fio_mark(raw: object) -> frozenset[str] | None:
    """ФИО как МНОЖЕСТВО слов в латинице — чтобы сравнивать людей, а не записи.

    Сравнение целых строк здесь выбрасывало блок с настоящими документами.
    Живой ответ несёт имя одного человека тремя записями, и одна из них —
    «Клочкова klochkova Елена elena Николаевна»: кириллица и транслит
    вперемешку в одном поле. Как строка она не равна «Клочкова Елена
    Николаевна», то есть считалась ДРУГИМ человеком, — и блок, в котором лежат
    паспорт и СНИЛС, отбраковывался как чужой.

    Множество слов в латинице снимает и разную запись, и порядок, и дубли:
    {klochkova, elena, nikolaevna} у всех трёх записей. Сравнение множеств —
    в :func:`_kin`, и оно НЕ на равенство: имя без отчества это тот же
    человек, а не другой.
    """
    words = {translit_ru(part) for part in str(raw).split()}
    words.discard("")
    return frozenset(words) or None


def _kin(
    rows: list[RecordDict], anchor: RecordDict | None
) -> tuple[list[RecordDict], list[tuple[str, RecordDict]]]:
    """Якорь и блоки, которые ему НЕ ПРОТИВОРЕЧАТ. Порядок ответа.

    Противоречие — это когда у якоря и у блока есть годный идентификатор одного
    вида и они РАЗНЫЕ: другое ФИО, другой паспорт, другой СНИЛС, другая дата
    рождения. Такой блок про другого человека, и брать из него недостающее
    нельзя.

    Это главная защита разбора, и вот от чего. Находки в ответе объединяет ОДИН
    ТОЛЬКО НОМЕР ТЕЛЕФОНА, а номером пользуются и родственники, и прежние
    владельцы номера: в живом ответе рядом с владелицей лежат ещё три человека
    с другими ФИО. Разбор, добиравший недостающее «по всему ответу», однажды
    взял бы дату рождения одного человека к паспорту другого — и собрал бы
    личность, которой не существует. По отчёту это не проверить: он выглядел бы
    совершенно обычно.

    Правило именно «не противоречит», а не «совпадает хоть чем-то», и разница
    существенна. Блок, где лежит один голый ИНН без имени, не совпадает с
    якорем ни по чему — но и не спорит с ним, и выбросить его значило бы
    потерять поле ради подозрения. Блок с другой фамилией спорит прямо, и его
    довод сильнее.

    Негодные значения в счёт не идут ни с одной стороны: СНИЛС с несошедшейся
    контрольной суммой — не СНИЛС, и отвергать по нему чужой блок не за что.
    """
    if anchor is None:
        return list(rows), []
    mine = _marks(anchor)
    kin = [anchor]
    # ПО КАКОМУ ПРИЗНАКУ блок отвергнут И ЧТО В НЁМ БЫЛО — для лога, см.
    # :func:`_rejection_report`.
    #
    # Без этого отбраковка невидима, а стоит она дорого: блок с верным адресом,
    # выброшенный по спорному признаку, выглядит как «поставщик такого адреса
    # не присылал». Ровно это и случилось — адрес из самой доверенной утечки не
    # дошёл даже до выбора, и отличить «отбросили» от «не было» было нечем.
    rejected: list[tuple[str, RecordDict]] = []
    for row in rows:
        if row is anchor:
            continue
        theirs = _marks(row)
        clash = next(
            (
                kind
                for kind, value in theirs.items()
                if kind in mine and _contradicts(kind, mine[kind], value)
            ),
            None,
        )
        if clash is not None:
            rejected.append((clash, row))
            continue
        kin.append(row)
    return kin, rejected


def _rejection_report(rejected: list[tuple[str, RecordDict]]) -> dict[str, object]:
    """Отбраковка двумя строками: по какому признаку и ЧТО с ней уехало.

    Счётчика признаков оказалось мало. «Паспорт не вытащился» разошлось на два
    объяснения — поставщик прислал меньше блоков или блок с паспортом выбросили
    мы, — и различить их по логу было нечем: в обоих случаях паспорта в
    ``found`` нет, а ``dropped`` говорит только «четыре блока по ФИО».

    Теперь говорит: если среди отброшенных был паспорт — выбросили мы, и
    чинить надо якорь и сверку. Если не был — спрашивать надо поставщика.

    ТОЛЬКО ИМЕНА ПОЛЕЙ. Значения в лог не идут никогда: он живёт дольше отчёта
    и расходится шире. И числа — СТРОКАМИ: страж лога вычёркивает всё, что
    лежит под ключом с именем чувствительного поля, и счётчик
    ``{'birth_date': 3}`` уехал в лог как ``{'birth_date': '<redacted>'}`` —
    ровно в тот день, когда это число и было ответом.
    """
    counts = Counter(kind for kind, _ in rejected)
    # Адрес здесь ЕСТЬ, в отличие от подсчёта признаков личности: он не
    # опознаёт человека, но теряется вместе с блоком, и теряется дороже всех —
    # только он открывает ЕГРН. Имени утечки в этом списке не место: оно не то,
    # что мы потеряли, а пометка на блоке.
    carried = {
        field
        for _, row in rejected
        for field, keys in _field_keys().items()
        if field != "origin" and _first(row, *keys) is not None
    }
    return {
        "dropped": [f"{kind}:{counts[kind]}" for kind in sorted(counts)],
        "dropped_carried": sorted(carried),
    }


def _contradicts(kind: str, mine: object, theirs: object) -> bool:
    """Спорят ли два признака одного вида. Не «различаются», а СПОРЯТ.

    Для паспорта, СНИЛСа и даты рождения это одно и то же: другое значение —
    другой человек. Для ИМЕНИ — нет, и разница стоила блока с документами.

    Имя сравнивается множествами слов (:func:`_read_fio_mark`), и неполное имя
    полному не противоречит: «Клочкова Елена» — тот же человек, что «Клочкова
    Елена Николаевна», просто записанный короче, и в живом ответе такой блок
    есть. Спор — это когда ни одно множество не вложено в другое: «Клочкова
    Мария» рядом с «Клочкова Елена Николаевна» — две разные женщины.
    """
    if kind == "fio" and isinstance(mine, frozenset) and isinstance(theirs, frozenset):
        return not (mine <= theirs or theirs <= mine)
    return mine != theirs


def _pick[T](
    kin: list[RecordDict],
    read: Callable[[object], T | None],
    *keys: str,
) -> T | None:
    """Первое значение, которое ``read`` признал годным, среди блоков родни.

    Порядок — тот, в котором записи пришли, начиная с якоря. Родня уже
    отобрана: здесь остаётся выбрать годное, а не решать, чьё оно.
    """
    for row in kin:
        raw = _first(row, *keys)
        if raw is None:
            continue
        value = read(raw)
        if value is not None:
            return value
    return None


def _issue_date(kin: list[RecordDict], passport: str | None) -> date | None:
    """Дата выдачи — только у ТОГО ЖЕ паспорта, который мы взяли.

    Отдельного поля под неё поставщик не отдаёт: на живом ответе она лежит
    внутри ``passport_info`` — свободным текстом вида «выдан … 15.01.2015», и
    только в блоках одной медицинской утечки. В том же ответе рядом лежат ещё
    два документа с другими номерами (семь и девять цифр), и у них своя дата.

    Поэтому дата берётся не «первая найденная», а из блока, где номер паспорта
    совпадает с выбранным. Приписать дату выдачи одного документа к номеру
    другого — это ошибка, которую в заявлении заметит только суд.
    """
    if not passport:
        return None
    for row in kin:
        if _read_passport(_first(row, "passport", "passport_number") or "") != passport:
            continue
        clean = _first(row, "passport_date", "passport_issued", "issue_date")
        if clean is not None and (parsed := _read_day(clean)) is not None:
            return parsed
        text = row.get("passport_info")
        found = _DATE_IN_TEXT.search(str(text)) if text else None
        if found is not None and (parsed := _read_day(found.group(0))) is not None:
            return parsed
    return None


#: Дата внутри свободного текста. Два формата, потому что оба встречаются в
#: одном и том же ответе.
_DATE_IN_TEXT = re.compile(r"\b\d{2}[.\-/]\d{2}[.\-/]\d{4}\b|\b\d{4}-\d{2}-\d{2}\b")


def _first(row: RecordDict, *keys: str) -> Any:
    """Первое непустое из синонимов поля в одной записи ответа.

    Синонимы нужны потому, что поставщик не один: у кого ``fio``, у кого
    ``full_name``. Пустая строка не считается значением — иначе она заслонила
    бы заполненный синоним рядом.
    """
    for key in keys:
        value = row.get(key)
        if value:
            return value
    return None


def _read_day(raw: object) -> date | None:
    """Дата из строки поставщика — в любом из форматов, которые он шлёт.

    Одна функция на дату рождения и на дату выдачи паспорта: формат у них один
    и тот же, а два разбора разошлись бы на первой правке.
    """
    return parse_date(str(raw))


def _read_passport(raw: object) -> str | None:
    """Паспорт РФ из строки поставщика.

    Источник подписывает вид документа словами — «Паспорт гражданина РФ 4510
    123456», «Загранпаспорт», «Паспорт иностранного гражданина». Нормализация
    оставляет цифры, и негодные отсеиваются длиной: у загранпаспорта их девять,
    у иностранного семь, и мост ФНС на них ответит пустотой за наши деньги.
    """
    return normalize_passport(str(raw))


def _read_snils(raw: object) -> str | None:
    """СНИЛС из строки поставщика — с проверкой контрольной суммы.

    Проверка здесь не педантизм: в ответе одиннадцатизначные числа лежат в
    нескольких полях, и взять не то — значит вписать в заявление чужой
    идентификатор. Разбор живёт в :func:`normalize_snils`.
    """
    return normalize_snils(str(raw))


def build_phone_bridge(settings: Settings) -> PhoneNameProvider | None:
    """Мост, если он настроен, иначе ``None``.

    ``None``, а не выключенный провайдер: незаполненный мост не должен занимать
    строку в отчёте у тех, кто вводит ФИО и в переводе номера не нуждается.
    """
    if not settings.phone_bridge_enabled:
        return None
    return PhoneNameProvider(settings)
