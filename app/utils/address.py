"""Доходит ли адрес до помещения — один вопрос и один ответ на весь проект.

Зачем это правило вообще. Росреестр ищет объект по адресу, и **по адресу до дома
он отвечает ошибкой, а вызов всё равно оплачен** — проверено живьём. Поэтому
адрес без квартиры в ЕГРН не отправляется вовсе, а мосты, собирающие личность из
чужого ответа, предпочитают тот адрес, который до квартиры доходит.

Правило жило ТРЕМЯ копиями: в мосте по телефону, в мосте по ФИО и в провайдере
ЕГРН. Копии обошлись дорого ровно там, где и должны были: расширь одну — мосты
выбирают адрес с квартирой, а ЕГРН его всё равно отвергает; расширь другую —
наоборот. Здесь теперь один ответ на всех.

ДВЕ ФОРМЫ, И ВТОРАЯ ДОБАВЛЕНА ПО ЖИВЫМ ДАННЫМ

Первая — со словом: «кв 151», «квартира 5», «помещ. 12», «оф 3». Её и проверяли.

Вторая — числовым хвостом: ``г Москва, проезд Петровско-Разумовский,8,139``.
Квартира здесь есть, это 139, но слова «кв» нет, и правило со словом такой адрес
отвергало. Владелец назвал форму частой и подтвердил её двумя адресами из разных
регионов — оба заканчиваются двумя числами через запятую, дом и квартира.

ЧЕГО ЭТО СТОИТ, ЕСЛИ ВТОРАЯ ФОРМА ПОНЯТА НЕВЕРНО. Если последнее число окажется
не квартирой, а корпусом, Росреестр ответит ошибкой и вызов будет оплачен — два
рубля за должника. Отчёт при этом не соврёт: раздел скажет «не проверено» с
причиной от источника, а не «объект не найден». Поэтому форма требует РОВНО двух
чисел в конце: одинокое число — это дом без квартиры, и такой адрес по-прежнему
не отправляется.

ОДНО МЕСТО — ОДНА СТРОКА

Поставщик отдаёт один и тот же адрес в нескольких написаниях: «обл. Тестовая,
г. Тестов» и «обл Тестовая, г Тестов», «…Первый, 1» и «…Первый,1,». Владелец
увидел это в списке выбора: «в выборе тут 5 адресов, но они повторяются, может
мы будем приводить их к одному виду? который принимает егрн?» — из пяти адресов
разных мест там было три.

Отсюда две разные задачи, и путать их дорого.

ЧТО СЧИТАТЬ ОДНИМ МЕСТОМ — :func:`same_place` и :func:`is_same_place`. Сравнение
никому не показывается, поэтому в нём остаются только слова и числа, которые о
месте говорят: регистр, «ё», точки сокращений, запятые против пробелов, порядок
слов, страна, почтовый индекс, «г» с «городом» и маркеры «д» с «кв» различают не
адреса, а тех, кто их записывал. Сравнение решает и подсчёт частоты: без него
один адрес, записанный двумя способами, считался за два разных и частота —
главный здесь довод — считалась неверно.

Второй живой список показал, насколько далеко это расходится: восемь строк, пять
мест. Одна и та же квартира приехала тремя записями — «г Москва, проезд
Тестовый,8,139», «Москва г Москва, Тестовый проезд, д 8, кв 139» и «РОССИЯ,
127220, Москва г, вн.тер.г. округ Тестовый, Тестовый проезд, д. 8, кв. 139»:
другой порядок слов, другие маркеры, приставки конторы. Поэтому запись, которая
несёт всё то же и сверх того, считается тем же местом — при совпадении чисел и
не меньше двух общих слов.

КАКОЕ ИЗ НАПИСАНИЙ ПОКАЗАТЬ И ОТПРАВИТЬ — :func:`_preferred_spelling`. Здесь
действует правило проекта: кодом можно закреплять только проверенное живьём.
Поэтому написание не СОЧИНЯЕТСЯ — выбирается одно из тех, что прислал
поставщик, и предпочтение отдаётся форме без точек в сокращениях: ровно она
дважды прошла в ЕГРН («…проезд Тестовый,8,139» и «…б-р Первый,17,151»), а
форма с точками живьём не проверялась ни разу. Пробелы и пустые части
(:func:`tidy`) — единственное, что убирается: они не часть адреса.
"""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Iterable, Sequence

#: Слово, называющее помещение, и число за ним.
_PREMISES_WORD = re.compile(
    r"(?:кв|квартира|помещ\w*|пом\.?|оф(?:ис)?)\.?\s*№?\s*\d",
    re.IGNORECASE,
)

#: Число, возможно с одной буквой: «8», «17А», «12к» — так пишут дом.
_NUMBER = re.compile(r"^\d+[А-Яа-яA-Za-z]?$")

#: Сколько частей должно быть, чтобы числовому хвосту было на чём стоять:
#: улица, дом, квартира. Два числа без улицы перед ними адресом не являются.
MIN_PARTS = 3


def has_premises(address: str) -> bool:
    """Доходит ли адрес до квартиры или помещения.

    Обе формы равноправны: адрес со словом «кв» и адрес, заканчивающийся домом и
    квартирой через запятую.

    Строка сперва чистится (:func:`tidy`), и это не косметика: у «…Первый,17,151»
    и «…Первый,17,151,» разный ХВОСТ, и вторая без чистки читается как дом без
    квартиры. Стоило бы это бесплатного, но неверного отказа «нужен адрес с
    квартирой» под адресом, в котором квартира есть.
    """
    text = tidy(address)
    if _PREMISES_WORD.search(text):
        return True
    return _ends_with_house_and_flat(text)


def _ends_with_house_and_flat(address: str) -> bool:
    """``…Петровско-Разумовский,8,139`` — дом и квартира без слов.

    Требуются ровно два числа в конце и что-то нечисловое перед ними: улица.
    Одинокое число в конце — дом без квартиры, и это тот самый случай, ради
    которого правило и существует.
    """
    parts = [part.strip() for part in address.split(",")]
    if len(parts) < MIN_PARTS:
        return False
    *head, house, flat = parts
    if not (_NUMBER.match(house) and _NUMBER.match(flat)):
        return False
    # Перед домом обязана стоять улица, а не третье число: «8,139,2» — это не
    # адрес, а обрывок, и угадывать в нём квартиру не из чего.
    return not _NUMBER.match(head[-1])


#: Короче этого адресом не бывает: «Москва» или обрывок поля.
MIN_ADDRESS_LENGTH = 10

#: Запятая, за которой идёт ещё одна: пустая часть, адресом не являющаяся.
_REPEATED_COMMA = re.compile(r",(?:\s*,)+")

#: Пробелы и запятые — в ключе сравнения они не различаются (см. :func:`same_place`).
_SEPARATORS = re.compile(r"[\s,]+")


def tidy(address: str) -> str:
    """Адрес без того, что адресом не является: лишних пробелов и пустых частей.

    Убирается ТОЛЬКО это. Порядок частей, сокращения и пробелы вокруг запятых
    остаются как их написал поставщик: по правилу проекта в платный источник
    уходит проверенная живьём строка, а не сочинённая нами.
    """
    text = _REPEATED_COMMA.sub(",", " ".join(address.split()))
    return text.strip(" ,")


#: Слова, которые о МЕСТЕ не говорят ничего: страна, уровни деления и маркеры
#: дома с квартирой. В одной записи они есть, в другой нет — а место одно.
#: Список закрытый и короткий: выбросить лишнее значит склеить разные адреса.
