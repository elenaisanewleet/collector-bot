"""Доходит ли адрес до помещения — один вопрос и один ответ на весь проект.

Зачем это правило вообще. Росреестр ищет объект по адресу, и **по адресу до дома
он отвечает ошибкой, а вызов всё равно оплачен** — проверено живьём. Поэтому
адрес без квартиры в ЕГРН не отправляется вовсе, а мосты, собирающие личность из
чужого ответа, предпочитают тот адрес, который до квартиры доходит.

Правило жило ТРЕМЯ копиями: в мосте по телефону, в мосте по ФИО и в провайдере
ЕГРН. Копии обошлись дорого ровно там, где и должны были: расширь одну — мосты
выбирают адрес с квартирой, а ЕГРН его всё равно отвергает; расширь другую —
наоборот. Здесь теперь один ответ на всех.

ДВЕ ФОРМЫ, И ВТОРАЯ ДОБАВЛЕНА ПО ЖИВЫМ ДАННЫМ

Первая — со словом: «кв 151», «квартира 5», «помещ. 12», «оф 3». Её и проверяли.

Вторая — числовым хвостом: ``г Москва, проезд Петровско-Разумовский,8,139``.
Квартира здесь есть, это 139, но слова «кв» нет, и правило со словом такой адрес
отвергало. Владелец назвал форму частой и подтвердил её двумя адресами из разных
регионов — оба заканчиваются двумя числами через запятую, дом и квартира.

ЧЕГО ЭТО СТОИТ, ЕСЛИ ВТОРАЯ ФОРМА ПОНЯТА НЕВЕРНО. Если последнее число окажется
не квартирой, а корпусом, Росреестр ответит ошибкой и вызов будет оплачен — два
рубля за должника. Отчёт при этом не соврёт: раздел скажет «не проверено» с
причиной от источника, а не «объект не найден». Поэтому форма требует РОВНО двух
чисел в конце: одинокое число — это дом без квартиры, и такой адрес по-прежнему
не отправляется.
"""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Iterable

#: Слово, называющее помещение, и число за ним.
_PREMISES_WORD = re.compile(
    r"(?:кв|квартира|помещ\w*|пом\.?|оф(?:ис)?)\.?\s*№?\s*\d",
    re.IGNORECASE,
)

#: Число, возможно с одной буквой: «8», «17А», «12к» — так пишут дом.
_NUMBER = re.compile(r"^\d+[А-Яа-яA-Za-z]?$")

#: Сколько частей должно быть, чтобы числовому хвосту было на чём стоять:
#: улица, дом, квартира. Два числа без улицы перед ними адресом не являются.
MIN_PARTS = 3


def has_premises(address: str) -> bool:
    """Доходит ли адрес до квартиры или помещения.

    Обе формы равноправны: адрес со словом «кв» и адрес, заканчивающийся домом и
    квартирой через запятую.
    """
    if _PREMISES_WORD.search(address):
        return True
    return _ends_with_house_and_flat(address)


def _ends_with_house_and_flat(address: str) -> bool:
    """``…Петровско-Разумовский,8,139`` — дом и квартира без слов.

    Требуются ровно два числа в конце и что-то нечисловое перед ними: улица.
    Одинокое число в конце — дом без квартиры, и это тот самый случай, ради
    которого правило и существует.
    """
    parts = [part.strip() for part in address.split(",")]
    if len(parts) < MIN_PARTS:
        return False
    *head, house, flat = parts
    if not (_NUMBER.match(house) and _NUMBER.match(flat)):
        return False
    # Перед домом обязана стоять улица, а не третье число: «8,139,2» — это не
    # адрес, а обрывок, и угадывать в нём квартиру не из чего.
    return not _NUMBER.match(head[-1])


#: Короче этого адресом не бывает: «Москва» или обрывок поля.
MIN_ADDRESS_LENGTH = 10


def pick_address(candidates: Iterable[str]) -> str | None:
    """Самый подтверждённый адрес из ответа — или ``None``, если годных нет.

    ПОЧЕМУ НЕ «ПЕРВЫЙ». Поставщик отвечает свалкой блоков из разных утечек, и
    адресов в ответе несколько: прописка, фактический, старый. Правило «первый с
    квартирой» опиралось на порядок выдачи, то есть на случайность — порядок
    задаёт поставщик, а не жизнь должника.

    Владелец предложил лучшее: «он в ответе встречается чаще всего». Это не
    вкус, а довод — блоки собраны из НЕЗАВИСИМЫХ источников, и адрес,
    повторившийся в нескольких, подтверждён несколькими утечками сразу, а
    одиночный не подтверждён ничем. Порядок остаётся, но только как способ
    разрешить равенство.

    Адрес с квартирой по-прежнему сильнее адреса до дома, и это не про
    подтверждённость, а про деньги: только такой примет Росреестр. Поэтому
    сначала выбирается из тех, что доходят до помещения, и лишь когда таких нет
    — из остальных, чтобы показать в карточке хоть что-то.
    """
    seen: list[tuple[str, str]] = []
    for raw in candidates:
        text = " ".join(str(raw).split())
        if len(text) >= MIN_ADDRESS_LENGTH:
            seen.append((_comparable(text), text))
    if not seen:
        return None
    with_premises = [pair for pair in seen if has_premises(pair[1])]
    return _most_confirmed(with_premises or seen)


def _most_confirmed(pairs: list[tuple[str, str]]) -> str:
    """Чаще всего встреченный, при равенстве — встреченный раньше."""
    counts = Counter(key for key, _ in pairs)
    best_key = max(counts, key=lambda key: (counts[key], -_first_index(pairs, key)))
    return next(text for key, text in pairs if key == best_key)


def _first_index(pairs: list[tuple[str, str]], key: str) -> int:
    return next(index for index, (candidate, _) in enumerate(pairs) if candidate == key)


def _comparable(address: str) -> str:
    """Ключ сравнения: одно и то же место, записанное по-разному, — один адрес.

    Регистр и пробелы вокруг запятых различают не адреса, а тех, кто их
    записывал. Без приведения «г Ульяновск, б-р Фестивальный,17,151» и
    «г Ульяновск, б-р Фестивальный, 17, 151» считались бы двумя разными
    адресами, и частота — главный здесь довод — считалась бы неверно.
    """
    return re.sub(r"\s*,\s*", ",", address.strip().lower())


__all__ = ["MIN_ADDRESS_LENGTH", "has_premises", "pick_address"]
