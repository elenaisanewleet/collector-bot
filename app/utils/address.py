"""Доходит ли адрес до помещения — один вопрос и один ответ на весь проект.

Зачем это правило вообще. Росреестр ищет объект по адресу, и **по адресу до дома
он отвечает ошибкой, а вызов всё равно оплачен** — проверено живьём. Поэтому
адрес без квартиры в ЕГРН не отправляется вовсе, а мосты, собирающие личность из
чужого ответа, предпочитают тот адрес, который до квартиры доходит.

Правило жило ТРЕМЯ копиями: в мосте по телефону, в мосте по ФИО и в провайдере
ЕГРН. Копии обошлись дорого ровно там, где и должны были: расширь одну — мосты
выбирают адрес с квартирой, а ЕГРН его всё равно отвергает; расширь другую —
наоборот. Здесь теперь один ответ на всех.

ДВЕ ФОРМЫ, И ВТОРАЯ ДОБАВЛЕНА ПО ЖИВЫМ ДАННЫМ

Первая — со словом: «кв 151», «квартира 5», «помещ. 12», «оф 3». Её и проверяли.

Вторая — числовым хвостом: ``г Москва, проезд Петровско-Разумовский,8,139``.
Квартира здесь есть, это 139, но слова «кв» нет, и правило со словом такой адрес
отвергало. Владелец назвал форму частой и подтвердил её двумя адресами из разных
регионов — оба заканчиваются двумя числами через запятую, дом и квартира.

ЧЕГО ЭТО СТОИТ, ЕСЛИ ВТОРАЯ ФОРМА ПОНЯТА НЕВЕРНО. Если последнее число окажется
не квартирой, а корпусом, Росреестр ответит ошибкой и вызов будет оплачен — два
рубля за должника. Отчёт при этом не соврёт: раздел скажет «не проверено» с
причиной от источника, а не «объект не найден». Поэтому форма требует РОВНО двух
чисел в конце: одинокое число — это дом без квартиры, и такой адрес по-прежнему
не отправляется.
"""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Iterable

#: Слово, называющее помещение, и число за ним.
_PREMISES_WORD = re.compile(
    r"(?:кв|квартира|помещ\w*|пом\.?|оф(?:ис)?)\.?\s*№?\s*\d",
    re.IGNORECASE,
)

#: Число, возможно с одной буквой: «8», «17А», «12к» — так пишут дом.
_NUMBER = re.compile(r"^\d+[А-Яа-яA-Za-z]?$")

#: Сколько частей должно быть, чтобы числовому хвосту было на чём стоять:
#: улица, дом, квартира. Два числа без улицы перед ними адресом не являются.
MIN_PARTS = 3


def has_premises(address: str) -> bool:
    """Доходит ли адрес до квартиры или помещения.

    Обе формы равноправны: адрес со словом «кв» и адрес, заканчивающийся домом и
    квартирой через запятую.
    """
    if _PREMISES_WORD.search(address):
        return True
    return _ends_with_house_and_flat(address)


def _ends_with_house_and_flat(address: str) -> bool:
    """``…Петровско-Разумовский,8,139`` — дом и квартира без слов.

    Требуются ровно два числа в конце и что-то нечисловое перед ними: улица.
    Одинокое число в конце — дом без квартиры, и это тот самый случай, ради
    которого правило и существует.
    """
    parts = [part.strip() for part in address.split(",")]
    if len(parts) < MIN_PARTS:
        return False
    *head, house, flat = parts
    if not (_NUMBER.match(house) and _NUMBER.match(flat)):
        return False
    # Перед домом обязана стоять улица, а не третье число: «8,139,2» — это не
    # адрес, а обрывок, и угадывать в нём квартиру не из чего.
    return not _NUMBER.match(head[-1])


#: Короче этого адресом не бывает: «Москва» или обрывок поля.
MIN_ADDRESS_LENGTH = 10


def pick_address(candidates: Iterable[str], *, preferred: Iterable[str] = ()) -> str | None:
    """Адрес должника из ответа поставщика — или ``None``, если годных нет.

    ``preferred`` — адреса ОПОРНОГО блока, того самого, из которого собрана вся
    остальная личность. Если в нём есть годный адрес, он и побеждает; частота
    считается только когда опорный блок адреса не назвал вовсе.

    ПОЧЕМУ ОПОРНЫЙ БЛОК ВПЕРЕДИ ЧАСТОТЫ, И ЧЕГО СТОИЛО ОБРАТНОЕ. Частота была
    доводом владельца — «он в ответе встречается чаще всего», — и довод
    настоящий: блоки собраны из независимых утечек, и повторившийся адрес
    подтверждён несколькими сразу. Но применили её ко ВСЕЙ родне, и на первом
    же живом ответе она выбрала владелице чужую квартиру: адрес по другому
    проспекту победил её собственный числом повторов.

    Разбор считает роднёй всякий блок, который опорному НЕ ПРОТИВОРЕЧИТ, — и
    блок с одним адресом и без единого идентификатора не противоречит никому.
    Несколько таких блоков перевешивают опорный, хотя именно он — единственный,
    про которого известно, что он о нашем человеке. Остальные поля этой
    асимметрии не знали: паспорт, СНИЛС, ИНН и дату рождения разбор берёт
    «первым годным начиная с якоря». Голосованием решался ровно один адрес — и
    ровно он оказался чужим.

    ЧТО ЗНАЧИТ «ГОДНЫЙ» И ПОЧЕМУ ДОМ ЯКОРЯ ЛУЧШЕ ЧУЖОЙ КВАРТИРЫ. Адрес с
    квартирой сильнее адреса до дома — только такой примет Росреестр. Но это
    предпочтение действует ВНУТРИ группы, а не между группами: если у опорного
    блока адрес только до дома, берётся он, а не чья-то квартира из соседнего
    блока. Дом нашего человека даёт бесплатный и честный отказ «нужен адрес с
    квартирой», а чужая квартира — оплаченный ответ про чужое имущество, и
    именно он выглядит как находка.
    """
    chosen = _best(preferred)
    return chosen if chosen is not None else _best(candidates)


#: Сколько адресов предлагать оператору на выбор. Восемь — столько их было в
#: живом ответе по одному номеру; больше на экране Telegram не читается, а
#: меньше отрезало бы верный.
MAX_OPTIONS = 8


def address_options(candidates: Iterable[str], *, preferred: Iterable[str] = ()) -> list[str]:
    """Кандидаты для выбора человеком: сначала лучший, потом остальные.

    ЗАЧЕМ ЭТО НУЖНО. Правильный адрес нельзя выбрать кодом — проверено
    четырьмя разными правилами на живом ответе, где кандидатов восемь. Ни
    частота, ни порядок выдачи, ни богатство блока признаком верного адреса не
    оказались: опорный блок, из которого взяты паспорт и СНИЛС, несёт адрес, по
    которому должник не живёт.

    Оператор это знает. Поэтому список доезжает до него целиком, а порядок
    здесь — не ранжирование, а вежливость: первым стоит тот, который
    подставлен по умолчанию (:func:`pick_address`), чтобы согласиться с ним
    было одним взглядом, а не поиском среди восьми.

    ПРЕДЛАГАЮТСЯ ВСЕ, А НЕ ТОЛЬКО ДОХОДЯЩИЕ ДО КВАРТИРЫ. Сначала список
    отбирал только их — с доводом «ЕГРН остальные не примет», — и довод
    оказался неверным дважды. Во-первых, кнопка выбора при одном годном
    кандидате не появлялась вовсе: владелец видел неверный адрес и не мог его
    сменить («по Олегу конкретный и выбрать не даёт»). Во-вторых, оператор,
    узнавший свой адрес в списке, дописывает квартиру сам — а не увидев его,
    не может и этого.

    Адрес с квартирой по-прежнему стоит выше: порядок здесь — не
    ранжирование, а вежливость, и годный для ЕГРН предлагается первым.
    """
    # Материализуются СРАЗУ: сюда приходят генераторы, и первый же проход по
    # ним оставил бы :func:`pick_address` ниже пустые руки — молча, потому что
    # исчерпанный генератор выглядит как отсутствие кандидатов.
    front = [str(raw) for raw in preferred]
    rest = [str(raw) for raw in candidates]
    seen: dict[str, str] = {}
    for raw in (*front, *rest):
        text = " ".join(raw.split())
        if len(text) < MIN_ADDRESS_LENGTH:
            continue
        seen.setdefault(_comparable(text), text)
    if not seen:
        return []
    # Годные для ЕГРН — выше: выбор из восьми строк начинается с тех, по
    # которым запрос вообще уйдёт.
    ordered = sorted(seen.values(), key=lambda item: not has_premises(item))
    best = pick_address(rest, preferred=front)
    if best is not None and best in ordered:
        ordered.remove(best)
        ordered.insert(0, best)
    return ordered[:MAX_OPTIONS]


def _best(candidates: Iterable[str]) -> str | None:
    """Лучший адрес одной группы: с квартирой, затем по подтверждённости.

    Частота внутри группы остаётся доводом владельца в полную силу: блоки
    собраны из независимых источников, и адрес, повторившийся в нескольких,
    подтверждён несколькими утечками, а одиночный не подтверждён ничем. Порядок
    выдачи остаётся, но только как способ разрешить равенство.
    """
    seen: list[tuple[str, str]] = []
    for raw in candidates:
        text = " ".join(str(raw).split())
        if len(text) >= MIN_ADDRESS_LENGTH:
            seen.append((_comparable(text), text))
    if not seen:
        return None
    with_premises = [pair for pair in seen if has_premises(pair[1])]
    return _most_confirmed(with_premises or seen)


def _most_confirmed(pairs: list[tuple[str, str]]) -> str:
    """Чаще всего встреченный, при равенстве — встреченный раньше."""
    counts = Counter(key for key, _ in pairs)
    best_key = max(counts, key=lambda key: (counts[key], -_first_index(pairs, key)))
    return next(text for key, text in pairs if key == best_key)


def _first_index(pairs: list[tuple[str, str]], key: str) -> int:
    return next(index for index, (candidate, _) in enumerate(pairs) if candidate == key)


def _comparable(address: str) -> str:
    """Ключ сравнения: одно и то же место, записанное по-разному, — один адрес.

    Регистр и пробелы вокруг запятых различают не адреса, а тех, кто их
    записывал. Без приведения «г Ульяновск, б-р Фестивальный,17,151» и
    «г Ульяновск, б-р Фестивальный, 17, 151» считались бы двумя разными
    адресами, и частота — главный здесь довод — считалась бы неверно.
    """
    return re.sub(r"\s*,\s*", ",", address.strip().lower())


